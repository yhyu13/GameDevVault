"""阻尼弹簧步进 —— 播种失败解 #1：更新顺序错（失败簇：数值积分/固定步长积分器）。

位置用【旧】速度更新（position-first 次序），速度再用同一时刻的加速度更新。
两种次序都是"辛格式"（symplectic），能量均有界、不会发散，静态读码看起来
完全正常；但轨迹与半隐式欧拉（先速度后位置）逐帧不同，单步即产生 O(dt) 偏差，
远大于 1e-4 容差。只有精确轨迹断言能拦截，能量界/收敛断言全部放行。
"""
def spring_step(x, v, k, c, rest, m, dt):
    a = (-k * (x - rest) - c * v) / m
    # BUG: 用旧速度更新位置（正确半隐式应先用新速度）
    x_new = x + v * dt
    v_new = v + a * dt
    return x_new, v_new
